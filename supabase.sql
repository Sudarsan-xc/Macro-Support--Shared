select setval(
  pg_get_serial_sequence('public.macros', 'id'),
  greatest(coalesce((select max(id) from public.macros), 1), 1),
  true
);

-- Enable live database change events for the website.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'macros'
  ) then
    alter publication supabase_realtime add table public.macros;
  end if;
end $$;
