-- MacroDesk shared database setup
-- Run this entire script in Supabase SQL Editor.

create table if not exists public.macros (
  id bigint generated by default as identity primary key,
  title text not null,
  category text default '',
  situation text default '',
  macro text not null,
  keywords text[] default '{}'::text[],
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.macros enable row level security;

-- Signed-in agents can use the shared library.
grant select, insert, update, delete on table public.macros to authenticated;
grant usage, select on sequence public.macros_id_seq to authenticated;

drop policy if exists "Agents can read macros" on public.macros;
create policy "Agents can read macros"
on public.macros for select
to authenticated
using (true);

drop policy if exists "Agents can add macros" on public.macros;
create policy "Agents can add macros"
on public.macros for insert
to authenticated
with check (true);

drop policy if exists "Agents can update macros" on public.macros;
create policy "Agents can update macros"
on public.macros for update
to authenticated
using (true)
with check (true);

drop policy if exists "Agents can delete macros" on public.macros;
create policy "Agents can delete macros"
on public.macros for delete
to authenticated
using (true);

-- Keep updated_at current.
create or replace function public.set_macros_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists macros_updated_at on public.macros;
create trigger macros_updated_at
before update on public.macros
for each row execute function public.set_macros_updated_at();

